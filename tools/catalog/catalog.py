HEADER = ("# GENERATED by ru-catalog (kokeb-labs/ci-tools, docs/ru-catalog.md): do not edit. Regenerated from the\n"
          "# lock file, each pinned driver's driver.yml, the MCU gate table and the integration results.\n")


# ------------------------------------------------------------------------------------------------------------ input

def api_get(path: str):
    base = os.environ.get("GITHUB_API_URL", "https://api.github.com").rstrip("/")
    token = os.environ.get("GITHUB_TOKEN", "")
    req = urllib.request.Request(base + path, headers={
        "Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "ci-tools-catalog",
        **({"Authorization": f"Bearer {token}"} if token else {})})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return r.status, json.loads(r.read().decode() or "null")
        except urllib.error.HTTPError as e:
            if e.code < 500 or attempt == 2:
                return e.code, None
        except (urllib.error.URLError, TimeoutError):
            if attempt == 2:
                return 0, None
    return 0, None


def git(root: str, *args: str) -> str:
    return subprocess.run(["git", "-C", root, *args], capture_output=True, text=True, check=False).stdout.strip()


def submodule_paths(root: str) -> dict[str, str]:
    """owner/repo (lower case) -> submodule path, from .gitmodules."""
    if not os.path.isfile(os.path.join(root, ".gitmodules")):
        return {}
    out, paths, urls = {}, {}, {}
    for line in git(root, "config", "-f", ".gitmodules", "--list").splitlines():
        key, _, value = line.partition("=")
        m = re.match(r"^submodule\.(.+)\.(path|url)$", key)
        if m:
            (paths if m.group(2) == "path" else urls)[m.group(1)] = value
    for name, url in urls.items():
        m = re.match(r"^(?:https://github\.com/|git@github\.com:)([^/]+/[^/]+?)(?:\.git)?/?$", url)
        if m and name in paths:
            out[m.group(1).lower()] = paths[name]
    return out


def read_text_at(root: str, subs: dict[str, str], repo: str, commit: str, path: str) -> tuple[str | None, str]:
    """A file of a pinned repository at its commit: (text, where it was read)."""
    sub = subs.get(repo.lower())
    if sub and os.path.isfile(os.path.join(root, sub, path)):
        head = git(os.path.join(root, sub), "rev-parse", "HEAD")
        if head == commit:
            with open(os.path.join(root, sub, path), encoding="utf-8") as fh:
                return fh.read(), f"{sub}/{path}"
    status, data = api_get(f"/repos/{repo}/contents/{path}?ref={commit}")
    if status == 200 and isinstance(data, dict) and "content" in data:
        return base64.b64decode(data["content"]).decode("utf-8"), f"{repo}@{commit[:12]}:{path}"
    return None, f"{repo}@{commit[:12]}:{path} (HTTP {status})"


def parse_gates(path: str) -> dict[str, list[tuple[str, str]]]:
    gates: dict[str, list[tuple[str, str]]] = {}
    if not path:
        return gates
    with open(path, encoding="utf-8") as fh:
        text = re.sub(r"#[^\n]*", "", fh.read())
    for name, mcu, periph in re.findall(r'"([A-Za-z0-9_]+):([A-Za-z0-9_]+):([A-Za-z0-9_]*)"', text):
        gates.setdefault(name, []).append((mcu, periph))
    return gates


def find_version(root: str, version_file: str) -> str:
    def parse(text: str) -> str:
        parts = {k: re.search(rf"set\(\s*\w*VERSION_{k}\s+(\d+)\s*\)", text) for k in ("MAJOR", "MINOR", "PATCH")}
        if all(parts.values()):
            return ".".join(parts[k].group(1) for k in ("MAJOR", "MINOR", "PATCH"))
        m = re.search(r"project\([^)]*\bVERSION\s+(\d+\.\d+\.\d+)", text) or re.search(
            r"(?<![\w.])(\d+\.\d+\.\d+)(?![\w.])", text)
        return m.group(1) if m else ""
    candidates = [version_file] if version_file else ["CMakeLists.txt"] + sorted(
        os.path.relpath(os.path.join(dp, f), root) for dp, _, fs in os.walk(os.path.join(root, "cmake"))
        for f in fs if "version" in f.lower() and f.endswith(".cmake"))
    for c in candidates:
        p = os.path.join(root, c)
        if os.path.isfile(p):
            with open(p, encoding="utf-8") as fh:
                text = fh.read()
            if c == "CMakeLists.txt" and not version_file:
                m = re.search(r"project\([^)]*\bVERSION\s+(\d+\.\d+\.\d+)", text)
                if m:
                    return m.group(1)
                continue
            v = parse(text)
            if v:
                return v
    return ""


def load_schema(schemas: str, name: str) -> dict:
    for d in ([schemas] if schemas else []) + [os.path.join(HERE, "schemas")]:
        p = os.path.join(d, name)
        if os.path.isfile(p):
            with open(p, encoding="utf-8") as fh:
                return json.load(fh)
    raise SystemExit(f"::error::schema {name} not found")


def validate(doc, schema: dict, label: str, errors: list[str]) -> None:
    import jsonschema  # noqa: PLC0415 (installed by the workflow)
    cls = jsonschema.validators.validator_for(schema)
    cls.check_schema(schema)
    for e in sorted(cls(schema).iter_errors(doc), key=lambda e: list(e.absolute_path)):
        where = "/".join(str(x) for x in e.absolute_path) or "(root)"
        errors.append(f"{label}: {where}: {e.message}")


# ------------------------------------------------------------------------------------------------------------ build

def build(a) -> tuple[dict, list[str], list[dict]]:
    errors: list[str] = []
    root = a.root
    with open(os.path.join(root, a.lock), encoding="utf-8") as fh:
        lock = yaml.safe_load(fh) or {}
    validate(lock, load_schema(a.schemas, "lock.schema.json"), a.lock, errors)
    driver_schema = load_schema(a.schemas, "driver.schema.json")
    gates = parse_gates(os.path.join(root, a.gates) if a.gates else "")
    version = find_version(root, a.version_file)
    if not version:
        errors.append("no version found: pass version_file (a CMake file with set(<X>_VERSION_MAJOR n) ..., "
                      "or a line X.Y.Z)")
    results: list = []
    sources_r = []
    for f in a.results:
        with open(f, encoding="utf-8") as fh:
            sources_r.append((f, fh.read()))
    if a.results_json.strip():
        sources_r.append(("results_json", a.results_json))
    for label, text in sources_r:
        rows = yaml.safe_load(text) or []  # YAML is a superset of JSON
        if not isinstance(rows, list):
            errors.append(f"{label}: expected a list of {{driver, mcu, rtos, result}}")
            continue
        results += rows
    subs = submodule_paths(root)
    drivers, sources = [], []
    for e in sorted((x for x in (lock.get("drivers") or []) if isinstance(x, dict)), key=lambda x: str(x.get("name"))):
        name, repo, tag, commit = (str(e.get(k, "")) for k in ("name", "repo", "tag", "commit"))
        text, where = read_text_at(root, subs, repo, commit, "driver.yml")
        sources.append({"name": name, "driver_yml": where})
        if text is None:
            errors.append(f"{name}: driver.yml not readable at the pinned commit ({where})")
            continue
        meta = yaml.safe_load(text) or {}
        before = len(errors)
        validate(meta, driver_schema, f"{name} driver.yml", errors)
        if len(errors) > before:
            continue
        if meta["name"] != name:
            errors.append(f"{name}: driver.yml name is {meta['name']}")
        want = re.sub(r"^v", "", re.sub(r"-rc\.\d+$", "", tag))
        if meta["version"] != want:
            errors.append(f"{name}: driver.yml version {meta['version']} is not the tag's {want}")
        mcus = [str(m).lower() for m in meta["mcus"]]
        gate = gates.get(name)
        if gate:
            if sorted({m.lower() for m, _ in gate}) != sorted(mcus) or {p for _, p in gate} != {meta["peripheral"]}:
                errors.append(f"{name}: driver.yml mcus {mcus} / peripheral {meta['peripheral']} disagree with the "
                              f"gate table {gate}; not an entry")
                continue
        elif mcus != ["any"] or meta["peripheral"] is not None:
            errors.append(f"{name}: needs mcus {mcus} / peripheral {meta['peripheral']} but the gate table has no "
                          "entry; not an entry")
            continue
        binding = None
        if a.binding_pattern:
            rel = a.binding_pattern.replace("{name}", name)
            if os.path.isfile(os.path.join(root, rel)):
                binding = re.split(r"(?:^|/)(?:inc|include)/", rel, maxsplit=1)[-1]
        configs = []
        for r in results:
            if not isinstance(r, dict) or not r.get("mcu"):
                continue
            if r.get("driver") not in (None, name):
                continue
            mcu = str(r["mcu"]).upper()
            if r.get("driver") is None and mcus != ["any"] and mcu.lower() not in mcus:
                continue
            res = str(r.get("result") or r.get("status") or "untested").lower()
            res = {"passed": "pass", "success": "pass", "failed": "fail", "failure": "fail",
                   "missing": "untested"}.get(res, res)
            cfg = {"mcu": mcu, "rtos": str(r.get("rtos") or "NONE").upper(), "result": res}
            if cfg not in configs:
                configs.append(cfg)
        configs.sort(key=lambda c: (c["mcu"], c["rtos"]))
        drivers.append({
            "name": name, "version": meta["version"], "repo": repo, "tag": tag, "commit": commit,
            "bus": list(meta["bus"]), "mcus": mcus, "peripheral": meta["peripheral"],
            "kb_core_min": meta["kb_core_min"], "binding": binding, "configs": configs,
        })
    doc = {"schema": 1, "kb_core": version or "0.0.0", "drivers": drivers}
    validate(doc, load_schema(a.schemas, "compat.schema.json"), "compat.yml", errors)
    return doc, errors, sources


class _Dumper(yaml.SafeDumper):
    """Block sequences indented under their key, as yamllint's indent-sequences rule wants."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def dump(doc: dict) -> str:
    return "---\n" + HEADER + yaml.dump(doc, Dumper=_Dumper, sort_keys=False, default_flow_style=None, width=120)


def cmd_build(a) -> int:
    doc, errors, sources = build(a)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(dump(doc))
    with open(os.path.splitext(a.out)[0] + ".json", "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=2, sort_keys=True)
        fh.write("\n")
    for e in errors:
        print(f"::error file={a.lock}::{e}")
    stale = False
    if a.check:
        committed_path = os.path.join(a.root, a.check)
        if not os.path.isfile(committed_path):
            print(f"::error::{a.check} does not exist; commit the generated catalogue (artifact)")
            stale = True
        else:
            with open(committed_path, encoding="utf-8") as fh:
                committed = yaml.safe_load(fh)
            if committed != doc:
                stale = True
                print(f"::error file={a.check}::{a.check} differs from the catalogue generated from the pins; "
                      "commit the generated file (in the artifact)")
                import difflib  # noqa: PLC0415
                print("".join(difflib.unified_diff(dump(committed or {}).splitlines(True), dump(doc).splitlines(True),
                                                   a.check, "generated")))
    lines = ["### Compatibility catalogue", "",
             f"Version {doc['kb_core']}, {len(doc['drivers'])} driver(s); "
             f"{'**' + str(len(errors)) + ' error(s)**' if errors else 'no error'}"
             f"{'; the committed file is **out of date**' if stale else ''}.", ""]
    if doc["drivers"]:
        lines += ["| Driver | Version | Tag | Commit | MCUs | Peripheral | Configurations |",
                  "| --- | --- | --- | --- | --- | --- | --- |"]
        for d in doc["drivers"]:
            cfgs = ", ".join(f"{c['mcu']}/{c['rtos']}: {c['result']}" for c in d["configs"]) or "-"
            lines.append(f"| `{d['name']}` | {d['version']} | `{d['tag']}` | `{d['commit'][:12]}` | "
                         f"{', '.join(d['mcus'])} | {d['peripheral'] or '-'} | {cfgs} |")
    if errors:
        lines += ["", *[f"- {e}" for e in errors]]
    text = "\n".join(lines) + "\n"
    print(text)
    if a.summary:
        with open(a.summary, "a", encoding="utf-8") as fh:
            fh.write(text)
    if a.github_output:
        with open(a.github_output, "a", encoding="utf-8") as fh:
            fh.write(f"drivers={len(doc['drivers'])}\nerrors={len(errors)}\nstale={'true' if stale else 'false'}\n"
                     f"version={doc['kb_core']}\n")
    return 1 if (errors or stale) else 0


# ------------------------------------------------------------------------------------------------------------- sbom

LICENSE_TEXTS = [
    ("MIT", r"Permission is hereby granted, free of charge"), ("Apache-2.0", r"Apache License,?\s+Version 2\.0"),
    ("BSD-3-Clause", r"Neither the name of"), ("BSD-2-Clause", r"Redistributions in binary form"),
    ("GPL-3.0-only", r"GNU GENERAL PUBLIC LICENSE\s+Version 3"), ("MPL-2.0", r"Mozilla Public License"),
]


def license_of(root: str, subs: dict[str, str], repo: str, commit: str) -> str:
    for name in ("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING"):
        text, _ = read_text_at(root, subs, repo, commit, name)
        if text:
            m = re.search(r"SPDX-License-Identifier:\s*([A-Za-z0-9.+-]+)", text)
            if m:
                return m.group(1)
            for spdx, rx in LICENSE_TEXTS:
                if re.search(rx, text):
                    return spdx
            return "NOASSERTION"
    return "NOASSERTION"


def own_license(root: str) -> str:
    for name in ("LICENSE", "LICENSE.md", "LICENSE.txt"):
        p = os.path.join(root, name)
        if os.path.isfile(p):
            with open(p, encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            m = re.search(r"SPDX-License-Identifier:\s*([A-Za-z0-9.+-]+)", text)
            if m:
                return m.group(1)
            for spdx, rx in LICENSE_TEXTS:
                if re.search(rx, text):
                    return spdx
    return "NOASSERTION"


def cmd_sbom(a) -> int:
    root = a.root
    with open(a.catalog, encoding="utf-8") as fh:
        cat = yaml.safe_load(fh) or {}
    subs = submodule_paths(root)
    head = git(root, "rev-parse", "HEAD") or "0" * 40
    epoch = git(root, "log", "-1", "--format=%ct") or os.environ.get("SOURCE_DATE_EPOCH", "0")
    stamp = datetime.datetime.fromtimestamp(int(epoch), datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    repo = a.repo or os.environ.get("GITHUB_REPOSITORY", a.name)
    comps = []
    for d in cat.get("drivers") or []:
        owner_repo = d["repo"]
        comps.append({
            "name": owner_repo.split("/")[-1], "group": owner_repo.split("/")[0], "version": d["version"],
            "tag": d["tag"], "commit": d["commit"], "repo": owner_repo,
            "license": license_of(root, subs, owner_repo, d["commit"]),
            "purl": f"pkg:github/{owner_repo}@{d['tag']}",
        })
    seed = json.dumps({"head": head, "components": comps}, sort_keys=True)
    serial = uuid.uuid5(uuid.NAMESPACE_URL, "ci-tools-sbom:" + hashlib.sha256(seed.encode()).hexdigest())
    root_ref = f"pkg:github/{repo}@v{a.version}"
    own = own_license(root)
    cdx = {
        "bomFormat": "CycloneDX", "specVersion": "1.6", "serialNumber": f"urn:uuid:{serial}", "version": 1,
        "metadata": {
            "timestamp": stamp,
            "tools": {"components": [{"type": "application", "name": "ci-tools ru-catalog",
                                      "group": "kokeb-labs"}]},
            "component": {"type": "library", "bom-ref": root_ref, "name": a.name, "version": a.version,
                          "purl": root_ref, "licenses": [{"license": {"id": own}}] if own != "NOASSERTION" else [],
                          "externalReferences": [{"type": "vcs", "url": f"https://github.com/{repo}",
                                                  "comment": f"commit {head}"}]},
        },
        "components": [{
            "type": "library", "bom-ref": c["purl"], "group": c["group"], "name": c["name"], "version": c["version"],
            "purl": c["purl"], "licenses": [{"license": {"id": c["license"]}}] if c["license"] != "NOASSERTION" else [],
            "externalReferences": [{"type": "vcs", "url": f"https://github.com/{c['repo']}",
                                    "comment": f"tag {c['tag']}, commit {c['commit']}"}],
            "properties": [{"name": "git:tag", "value": c["tag"]}, {"name": "git:commit", "value": c["commit"]}],
        } for c in comps],
        "dependencies": [{"ref": root_ref, "dependsOn": [c["purl"] for c in comps]}]
                        + [{"ref": c["purl"], "dependsOn": []} for c in comps],
    }

    def spdx_id(s: str) -> str:
        return "SPDXRef-" + re.sub(r"[^A-Za-z0-9.-]", "-", s)
    root_id = spdx_id("Package-" + a.name)
    spdx = {
        "spdxVersion": "SPDX-2.3", "dataLicense": "CC0-1.0", "SPDXID": "SPDXRef-DOCUMENT",
        "name": f"{a.name}-{a.version}",
        "documentNamespace": f"https://github.com/{repo}/sbom/{a.version}/{serial}",
        "creationInfo": {"created": stamp, "creators": ["Tool: ci-tools-ru-catalog"]},
        "packages": [{
            "SPDXID": root_id, "name": a.name, "versionInfo": a.version,
            "downloadLocation": f"git+https://github.com/{repo}@{head}", "filesAnalyzed": False,
            "licenseConcluded": own, "licenseDeclared": own, "copyrightText": "NOASSERTION",
            "externalRefs": [{"referenceCategory": "PACKAGE-MANAGER", "referenceType": "purl",
                              "referenceLocator": root_ref}],
        }] + [{
            "SPDXID": spdx_id("Package-" + c["name"]), "name": c["name"], "versionInfo": c["version"],
            "supplier": f"Organization: {c['group']}",
            "downloadLocation": f"git+https://github.com/{c['repo']}@{c['commit']}", "filesAnalyzed": False,
            "licenseConcluded": "NOASSERTION", "licenseDeclared": c["license"], "copyrightText": "NOASSERTION",
            "externalRefs": [{"referenceCategory": "PACKAGE-MANAGER", "referenceType": "purl",
                              "referenceLocator": c["purl"]}],
            "comment": f"tag {c['tag']}, commit {c['commit']}",
        } for c in comps],
        "relationships": [{"spdxElementId": "SPDXRef-DOCUMENT", "relationshipType": "DESCRIBES",
                           "relatedSpdxElement": root_id}]
                         + [{"spdxElementId": root_id, "relationshipType": "DEPENDS_ON",
                             "relatedSpdxElement": spdx_id("Package-" + c["name"])} for c in comps],
    }
    os.makedirs(a.out_dir, exist_ok=True)
    base = f"{a.name}-{a.version}"
    for suffix, doc in ((".cdx.json", cdx), (".spdx.json", spdx)):
        with open(os.path.join(a.out_dir, base + suffix), "w", encoding="utf-8") as fh:
            json.dump(doc, fh, indent=2, sort_keys=True)
            fh.write("\n")
    print(f"SBOM: {base}.cdx.json (CycloneDX 1.6), {base}.spdx.json (SPDX 2.3), {len(comps)} component(s)")
    return 0


