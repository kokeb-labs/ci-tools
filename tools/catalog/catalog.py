#!/usr/bin/env python3
"""The compatibility catalogue (compat.yml, schema 1) of a revision, from its pinned drivers; and the revision's SBOMs.
PyYAML and jsonschema (tools/catalog/requirements.txt).

  catalog.py build --root DIR --lock FILE [--gates FILE] [--version-file FILE] [--results FILE ...] [--results-json J]
                   [--binding-pattern PATTERN] [--schemas DIR] --out FILE [--check FILE] [--summary FILE]
                   [--github-output FILE]
  catalog.py sbom  --root DIR --catalog FILE --name NAME --version X.Y.Z --out-dir DIR [--repo OWNER/NAME]
  catalog.py pages --catalog FILE --files DIR --out DIR

build: every lock entry's driver.yml is read at its pinned commit, from the checked-out submodule (the .gitmodules
entry whose URL is the entry's repo) when it is there, else through the GitHub API with GITHUB_TOKEN. The lock, every
driver.yml and the result are validated against the JSON schemas (the bundled ones in schemas/, or the files of
the same name in --schemas: lock.schema.json, driver.schema.json, compat.schema.json). A driver whose mcus or
peripheral disagree with the gate table ("<name>:<MCU>:<peripheral>" strings) is an error, not an entry. configs come
from --results files and --results-json (JSON or YAML: a list of {driver (optional: every driver that allows the
MCU), mcu, rtos, result or status}, such as ru-cmake-matrix's results output), else none. The output is deterministic: drivers sorted by name, configs by MCU and RTOS, no timestamp. --check FILE
fails when FILE does not hold the same catalogue (compared as data, so its comments may differ).

sbom: CycloneDX 1.6 and SPDX 2.3 JSON of the revision: the repository itself and every pinned driver with its
version, tag, commit, repository, licence (from the submodule's LICENSE or the API) and package URL. Timestamps are
the HEAD commit's, so the files are reproducible.

pages: a static site (index.html, compat.json, compat.yml and the files of --files) for GitHub Pages.
"""

